-- +goose Up
-- Multi-repo GitOps registry (Feature A): an org can have many GitOps state
-- repos — platform baselines plus team-scoped repos — replacing the
-- single-repo-per-org model enforced by tenant_git_configs' PRIMARY KEY.
-- tenant_git_configs keeps org-level defaults; its legacy `repo` column is
-- backfilled here as the org's default platform repo.
CREATE TABLE tenant_git_repos (
    id            TEXT PRIMARY KEY,              -- ulid, generated by the store
    org_id        TEXT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    name          TEXT NOT NULL,                 -- display name, unique per org
    repo          TEXT NOT NULL,                 -- e.g. myorg/team-a-gitops
    provider      TEXT NOT NULL DEFAULT 'github',
    scope         TEXT NOT NULL DEFAULT 'team' CHECK (scope IN ('platform', 'team')),
    team_id       UUID REFERENCES teams(id) ON DELETE SET NULL,
    commit_policy TEXT NOT NULL DEFAULT 'direct',
    base_branch   TEXT NOT NULL DEFAULT 'main',
    is_default    BOOLEAN NOT NULL DEFAULT FALSE,
    -- Optional per-repo BYO GitHub App override (model B); same all-or-nothing
    -- credential-reference pattern as tenant_git_configs (migration 0022).
    github_app_id              BIGINT,
    github_app_installation_id BIGINT,
    github_app_key_secret      TEXT,   -- namespace/name of the ESO-rendered Secret
    github_app_key_key         TEXT,   -- data key inside the Secret
    github_app_api_base        TEXT,   -- NULL/'': github.com; else GHE https://<host>/api/v3
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (org_id, name),
    UNIQUE (org_id, repo),
    CONSTRAINT tenant_git_repo_app_all_or_none CHECK (
        (github_app_id IS NULL AND github_app_installation_id IS NULL
            AND github_app_key_secret IS NULL AND github_app_key_key IS NULL)
        OR (github_app_id IS NOT NULL AND github_app_installation_id IS NOT NULL
            AND github_app_key_secret IS NOT NULL AND github_app_key_key IS NOT NULL)),
    CONSTRAINT tenant_git_repo_api_base_requires_app CHECK (
        github_app_api_base IS NULL OR github_app_id IS NOT NULL),
    -- team_id is only meaningful for team-scoped repos.
    CONSTRAINT tenant_git_repo_team_scope CHECK (
        scope = 'team' OR team_id IS NULL)
);

-- At most one default repo per org (the fallback for new clusters and the
-- back-compat proxy target for tenant_git_configs.repo).
CREATE UNIQUE INDEX one_default_repo_per_org ON tenant_git_repos (org_id) WHERE is_default;
CREATE INDEX tenant_git_repos_org_idx ON tenant_git_repos (org_id);
CREATE INDEX tenant_git_repos_team_idx ON tenant_git_repos (team_id) WHERE team_id IS NOT NULL;

-- Back-compat backfill: the existing single repo per org becomes its default
-- platform repo named 'baseline'. The BYO app reference moves with it so
-- per-repo resolution keeps working; tenant_git_configs is left untouched
-- (org-level defaults + legacy fallback). The store generates real ULIDs for
-- new rows; a random hex id is fine for this one-shot backfill.
INSERT INTO tenant_git_repos (id, org_id, name, repo, provider, scope, commit_policy, base_branch, is_default,
                              github_app_id, github_app_installation_id, github_app_key_secret,
                              github_app_key_key, github_app_api_base)
SELECT lower(substr(md5(random()::text || clock_timestamp()::text), 1, 26)),
       org_id, 'baseline', repo, 'github', 'platform', commit_policy, base_branch, TRUE,
       github_app_id, github_app_installation_id, github_app_key_secret,
       github_app_key_key, github_app_api_base
FROM tenant_git_configs;

-- +goose Down
DROP TABLE IF EXISTS tenant_git_repos;
