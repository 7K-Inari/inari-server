-- First-class cluster addons (Feature C schema, shipped with Feature A so M3
-- needs no second migration pass): discovered/adopted/managed addons per
-- cluster, rendered into a tenant_git_repos row and synced by ArgoCD.
-- cluster_id is a plain TEXT column (no FK): the '*' sentinel marks
-- ApplicationSet fleet-wide rows that span clusters, matching the
-- polymorphic-ref convention used by resource_instances.
CREATE TABLE cluster_addons (
    id              TEXT PRIMARY KEY,            -- ulid, generated by the store
    org_id          TEXT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
    cluster_id      TEXT NOT NULL,               -- inventory cluster id, or '*' for fleet rows
    catalog_item    TEXT NOT NULL,               -- e.g. platform:cert-manager
    state           TEXT NOT NULL DEFAULT 'discovered'
                    CHECK (state IN ('discovered', 'adopting', 'managed', 'update_failed')),
    deploy_mode     TEXT NOT NULL DEFAULT 'application'
                    CHECK (deploy_mode IN ('application', 'applicationset')),
    repo_id         TEXT REFERENCES tenant_git_repos(id) ON DELETE SET NULL,
    repo_path       TEXT NOT NULL DEFAULT '',    -- e.g. addons/cert-manager
    source          JSONB NOT NULL,              -- SourceDescriptor (kind + helm/kro/... payload)
    chart_version   TEXT NOT NULL DEFAULT '',    -- denormalized for the version dropdown UX
    values          JSONB NOT NULL DEFAULT '{}',
    argocd_app      TEXT NOT NULL DEFAULT '',    -- e.g. inari-addon-<id> / inari-addonset-<id>
    health          TEXT NOT NULL DEFAULT '',    -- folded from the status stream
    sync            TEXT NOT NULL DEFAULT '',
    discovered_meta JSONB,                       -- what the scanner saw (release, namespace, version)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (cluster_id, catalog_item)
);

CREATE INDEX cluster_addons_org_idx ON cluster_addons (org_id);
CREATE INDEX cluster_addons_repo_idx ON cluster_addons (repo_id) WHERE repo_id IS NOT NULL;

